/** Avalia um tabuleiro 0x88 do ponto de vista das brancas (centipeões). */
export function evaluateBoard(board: ({ type: PieceSymbol; color: Color } | undefined)[]): number {
  let score = 0;
  let nonPawn = 0;
  for (let sq = 0; sq < 128; sq++) {
    if (sq & 0x88) {
      sq += 7;
      continue;
    }
    const p = board[sq];
    if (p && p.type !== 'p' && p.type !== 'k') nonPawn += PIECE_VALUE[p.type];
  }
  const endgame = nonPawn <= 2600;
  for (let sq = 0; sq < 128; sq++) {
    if (sq & 0x88) {
      sq += 7;
      continue;
    }
    const p = board[sq];
    if (!p) continue;
    const row = sq >> 4;
    const col = sq & 7;
    const idx = p.color === 'w' ? row * 8 + col : (7 - row) * 8 + col;
    const table = p.type === 'k' && endgame ? KING_END : PST[p.type];
    const v = PIECE_VALUE[p.type] + table[idx];
    score += p.color === 'w' ? v : -v;
  }
  return score;
}

/** Valor estratégico de uma reserva de energia (retornos decrescentes perto do teto). */
export function energyValue(e: number): number {
  const useful = Math.min(e, 160);
  return useful * 0.6 + Math.max(0, e - 160) * 0.1 - (e < 40 ? (40 - e) * 0.3 : 0);
}
